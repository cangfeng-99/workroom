def render_markdown():
    lines = [
        "# WorkRoom 个人版使用指南",
        "",
        INTRO,
        "",
        "指南仅描述当前单人本机版。练习项目是固定模板，任务全部待做，不代表代码、模型连接或检查已经完成。",
        "",
    ]
    for section in SECTIONS:
        lines.extend(["## " + section["title"], "", section["summary"], ""])
        lines.extend(f"{index}. {step}" for index, step in enumerate(section["steps"], 1))
        if section.get("example"):
            lines.extend(["", "> " + section["example"]])
        lines.append("")
    return "\n".join(lines) + "\n"
